/**
 * Токен — це ключ, за яким контейнер знаходить залежність.
 *
 * Клас можна резолвити безпосередньо за його конструктором: клас і є токеном.
 * Але інтерфейси в рантаймі не існують — після компіляції від них не лишається
 * нічого (стирання типів). Тому для інтерфейсів/абстракцій потрібен явний
 * токен: `symbol` або `string`, який ми реєструємо в контейнері вручну і потім
 * вказуємо через @Inject(token).
 */

// Конструктор будь-якого класу. `any[]` тут навмисно: аргументи ми підставляємо
// динамічно з метаданих, тому статично їх типізувати неможливо.
export type Constructor<T = unknown> = new (...args: any[]) => T;

// Усе, за чим контейнер уміє резолвити: сам клас, символ або рядок.
export type Token<T = unknown> = Constructor<T> | symbol | string;

/**
 * Приклад well-known токена для конфігурації застосунку.
 *
 * `Symbol.for('CONFIG')` бере символ із глобального реєстру — тому будь-де в коді
 * `Symbol.for('CONFIG') === CONFIG`. Саме це дає змогу реєструвати значення під
 * токеном в одному місці, а інжектити його @Inject(CONFIG) — в іншому.
 */
export const CONFIG = Symbol.for('CONFIG');
